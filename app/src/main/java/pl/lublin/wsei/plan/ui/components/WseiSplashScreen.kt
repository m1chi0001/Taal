/**
 * Ekran startowy wyświetlany podczas odtwarzania zaszyfrowanej sesji —
 * dzięki niemu przy zalogowanym użytkowniku nie mignie ekran logowania.
 */
@Composable
fun WseiSplashScreen(modifier: Modifier = Modifier) {
    val scale = remember { Animatable(0.6f) }
    LaunchedEffect(Unit) {
        scale.animateTo(
            targetValue = 1f,
            animationSpec = spring(
                dampingRatio = Spring.DampingRatioLowBouncy,
                stiffness = Spring.StiffnessMediumLow
            )
        )
    }
    val rotation by rememberInfiniteTransition(label = "splashRotation").animateFloat(
        initialValue = 0f,
        targetValue = 360f,
        animationSpec = infiniteRepeatable(tween(14_000, easing = LinearEasing), RepeatMode.Restart),
        label = "splashCookieRotation"
    )

    Box(
        modifier = modifier
            .fillMaxSize()
            .background(MaterialTheme.colorScheme.surface),
        contentAlignment = Alignment.Center
    ) {
        Column(
            horizontalAlignment = Alignment.CenterHorizontally,
            verticalArrangement = Arrangement.spacedBy(20.dp),
            modifier = Modifier.scale(scale.value)
        ) {
            Box(contentAlignment = Alignment.Center) {
                Box(
                    modifier = Modifier
                        .size(132.dp)
                        .rotate(rotation)
                        .clip(M3XCookieShape)
                        .background(MaterialTheme.colorScheme.primaryContainer)
                )
                Icon(
                    imageVector = WseiIcons.TaalVolcano,
                    contentDescription = null,
                    tint = MaterialTheme.colorScheme.onPrimaryContainer,
                    modifier = Modifier.size(64.dp)
                )
            }
            Text(
                text = "Taal",
                style = MaterialTheme.typography.displaySmall,
                fontWeight = FontWeight.Bold,
                color = MaterialTheme.colorScheme.onSurface
            )
        }
    }
}
